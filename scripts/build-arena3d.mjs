// Bundle the 3D arena (src/arena3d, three.js) into web/arena3d.js: one minified classic Web Worker script the client
// starts only after its title screen is up, rendering on an OffscreenCanvas off the main thread. three.js is a dev dependency, so builders never install it: the bundle is committed, and CI
// checks it matches the source. `pnpm arena3d` rebuilds it.
import { readFileSync, statSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const at = (p) => fileURLToPath(new URL(p, import.meta.url));
const out = at('../web/arena3d.js');
await build({
  entryPoints: [at('../src/arena3d/worker.ts')],
  outfile: out,
  bundle: true, format: 'iife', platform: 'browser', target: 'es2022', minify: true, legalComments: 'none',
  banner: { js: '// Tessaract 3D arena (three.js, MIT). Generated by scripts/build-arena3d.mjs from src/arena3d: do not edit.' },
  logLevel: 'warning',
});
const kb = (n) => `${Math.round(n / 1024)} KB`;
console.log(`built web/arena3d.js: ${kb(statSync(out).size)} (${kb(gzipSync(readFileSync(out)).length)} gzipped)`);
