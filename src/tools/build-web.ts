/**
 * Build the static site's game data: the rules engine, the game config and the collection the
 * champions come from.
 *
 *   deckwright web <game.json> [--collection <cards.json>] [--art-root <dir>] [--out web]
 *
 * Writes:
 *   <out>/engine/deckwright.js   core + sessions as one ES module (the same rules the relay and LitNode run)
 *   <out>/data/game.json         the game config
 *   <out>/data/collection.json   the collection snapshot (cards with tokenId, name, kind, element, stats, art)
 *   <out>/assets/art/*           every card's art, with `art` rewritten to ./assets/art/<file>
 *
 * The collection is a `deckwright snapshot` file (or the Rapture snapshot shape). Each card's `art` is
 * found next to the snapshot first, then under `--art-root` (default: two folders above the snapshot,
 * as in <site>/assets/<collection>/cards.json). Without --collection the site still works: players
 * fight with a neutral champion.
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';

import * as esbuild from 'esbuild';

import { die, flag, litnodeHash, parseArgs, readGame } from './common';
import { pkgPath } from './paths';

const args = parseArgs();
const gamePath = args._[0] ?? die('usage: deckwright web <game.json> [--collection <cards.json>] [--art-root <dir>] [--out web]');
const game = readGame(gamePath);
const collectionPath = flag(args, 'collection') ? resolve(flag(args, 'collection')!) : null;
const artRoot = collectionPath ? resolve(flag(args, 'art-root') ?? join(dirname(collectionPath), '..', '..')) : null;
const outDir = resolve(flag(args, 'out') ?? 'web');

const result = await esbuild.build({
  entryPoints: [pkgPath('src', 'browser.ts')],
  bundle: true, format: 'esm', platform: 'browser', target: 'es2020',
  write: false, minify: false, treeShaking: true, legalComments: 'none', logLevel: 'silent', charset: 'utf8',
});
const code = result.outputFiles[0].text;
const header = `// GENERATED by \`deckwright web\`. Do not edit: rebuild instead.\n// rules hash ${litnodeHash('web', code).slice(0, 16)}\n`;

for (const d of ['engine', 'data', 'assets/art']) mkdirSync(join(outDir, d), { recursive: true });
writeFileSync(join(outDir, 'engine', 'deckwright.js'), header + code);
writeFileSync(join(outDir, 'data', 'game.json'), `${JSON.stringify(game, null, 2)}\n`);

interface SnapshotCard { tokenId: string; art?: string; [k: string]: unknown }
const snap = collectionPath
  ? (JSON.parse(readFileSync(collectionPath, 'utf8')) as { collection: Record<string, unknown>; cards: SnapshotCard[] })
  : { collection: { name: game.title, chainId: null, address: null }, cards: [] as SnapshotCard[] };
let copied = 0;
for (const c of snap.cards) {
  if (!c.art) continue;
  if (/^https?:\/\//.test(c.art)) { console.warn(`warning: ${c.tokenId} art is remote (${c.art}); the site's CSP serves local art only, so it is dropped. Re-run snapshot to download it.`); c.art = undefined; continue; }
  const candidates = [resolve(dirname(collectionPath!), c.art), resolve(artRoot!, c.art)];
  const from = candidates.find((p) => existsSync(p));
  if (!from) die(`art for token ${c.tokenId} not found: ${candidates.join(' or ')} (set --art-root)`);
  copyFileSync(from, join(outDir, 'assets', 'art', basename(from)));
  c.art = `./assets/art/${basename(from)}`;
  copied++;
}
// The site reads only what the duel needs; avatars and lore stay with the collection's own site.
const cards = snap.cards.map((c) => ({ tokenId: c.tokenId, slug: c.slug, name: c.name, epithet: c.epithet, kind: c.kind, element: c.element, faction: c.faction, stats: c.stats, art: c.art, image: c.image, metadata: c.metadata }));
writeFileSync(join(outDir, 'data', 'collection.json'), `${JSON.stringify({ collection: snap.collection, cards }, null, 2)}\n`);

const units = game.cards.filter((c) => c.type === 'unit');
const byToken = new Set(cards.map((c) => String(c.tokenId)));
const unmapped = units.filter((u) => u.token && !byToken.has(String(u.token.tokenId))).length;
console.log(`engine ${Buffer.byteLength(code)} bytes · game ${game.litnode.rulesetId} · ${cards.length} collection cards · ${copied} art files → ${outDir}`);
if (unmapped) console.warn(`warning: ${unmapped} unit card(s) name a token missing from the collection (they show without art)`);
