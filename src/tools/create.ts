/**
 * Scaffold a new game project: a starter game, the web client, the Vercel config and the Deckwright
 * skill (so an AI agent in the project knows the workflow), then build the site so it plays at once.
 *
 *   npx github:strodanodev/deckwright create my-tcg [--title "My TCG"] [--sdk <dependency spec>]
 *
 * --sdk is what the new project's package.json depends on. The default is the GitHub repo, until the
 * package is on npm (then it becomes `^<version>`). Use a `file:` path to test a local build.
 */
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join, resolve } from 'node:path';

import type { GameConfig } from '../core/types';
import { die, flag, parseArgs } from './common';
import { pkgPath } from './paths';

const args = parseArgs();
const target = resolve(args._[0] ?? die('usage: deckwright create <dir> [--title "My TCG"] [--sdk <dependency spec>]'));
if (existsSync(target) && readdirSync(target).length) die(`${target} exists and is not empty`);
const id = basename(target).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'my-tcg';
const title = flag(args, 'title') ?? id.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join(' ');
const sdk = flag(args, 'sdk') ?? 'github:strodanodev/deckwright';

mkdirSync(join(target, 'games'), { recursive: true });
const template = JSON.parse(readFileSync(pkgPath('templates', 'starter.game.json'), 'utf8')) as GameConfig;
const gameFile = `games/${id}.game.json`; // forward slashes: it lands in npm scripts and docs
writeFileSync(join(target, gameFile), `${JSON.stringify({ ...template, title, litnode: { ...template.litnode, rulesetId: `${id}.v1` } }, null, 2)}\n`);

// The hand-written site; engine/, data/ and assets/art/ are generated by `deckwright web` below.
mkdirSync(join(target, 'web'), { recursive: true });
for (const f of ['app.js', 'favicon.svg']) cpSync(pkgPath('web', f), join(target, 'web', f));
for (const d of ['ui', 'styles', 'lib']) cpSync(pkgPath('web', d), join(target, 'web', d), { recursive: true });
// The demo's "Build your own" page is Deckwright marketing, not the builder's: without its marker the client leaves it
// out and credits Deckwright on the title screen instead.
const page = readFileSync(pkgPath('web', 'index.html'), 'utf8').replace(/<!-- deckwright:funnel -->[\s\S]*?<!-- \/deckwright:funnel -->\n?/g, '');
writeFileSync(join(target, 'web', 'index.html'), page);
cpSync(pkgPath('vercel.json'), join(target, 'vercel.json'));
cpSync(pkgPath('templates', 'gauntlet.json'), join(target, 'gauntlet.json'));
// The skill also ships as a Claude Code plugin; a project copy means an agent opened in the game finds it too.
cpSync(pkgPath('plugin', 'skills', 'deckwright'), join(target, '.claude', 'skills', 'deckwright'), { recursive: true });

const run = (cmd: string): string => `deckwright ${cmd}`;
const pkg = {
  name: id,
  version: '0.1.0',
  private: true,
  type: 'module',
  scripts: {
    sim: run(`sim ${gameFile} --matches 300`),
    title: run(`title ${gameFile}`),
    web: run(`web ${gameFile}`),
    dev: run('dev'),
    relay: `${run('relay')}`,
  },
  devDependencies: { deckwright: sdk },
};
writeFileSync(join(target, 'package.json'), `${JSON.stringify(pkg, null, 2)}\n`);
writeFileSync(join(target, '.gitignore'), 'node_modules/\nrulesets/\n.vercel/\ncollection/\n');
writeFileSync(join(target, 'README.md'), `# ${title}

A trading card game made with Deckwright: one JSON file (\`${gameFile}\`) is the game.

\`\`\`bash
npm install
npm run dev          # http://127.0.0.1:4173 — play against the bot
npm run sim          # balance: bot vs bot, replay check
npm run web          # rebuild the site after editing the game
\`\`\`

Bring an NFT collection (ERC-721; ERC-6699 stats make champions):

\`\`\`bash
npx deckwright snapshot <collection address> --chain liteforge --out collection
npx deckwright import collection/cards.json --id ${id} --out games
npx deckwright web ${gameFile} --collection collection/cards.json
\`\`\`

Two players: \`TCG_DEV=1 TCG_GAME=${gameFile} npm run relay\`, then open the site twice with \`?relay=ws://127.0.0.1:7830&name=alice\` / \`&name=bob\`.
Deploy: \`vercel deploy --prod\` (static site in \`web/\`, headers in \`vercel.json\`).
The \`deckwright\` skill in \`.claude/skills\` walks an AI agent through all of this.
`);

console.log(`created ${target}`);
console.log('building the site…');
process.argv = [process.argv[0], 'deckwright web', join(target, gameFile), '--out', join(target, 'web')];
await import('./build-web');
console.log(`\nnext:\n  cd ${args._[0]}\n  npm install\n  npm run dev`);
